"""
Offline evaluation harness for the CalmConnect recommender.

Runs the live recommender (recommender.py, including the real DistilBERT
sentiment model) against the synthetic ground-truth set generated by
data/generate_eval_set.py, computes ranking metrics, and logs them to MLflow.

Metrics:
  - Precision@1: did the top recommendation match the ground-truth top pick?
  - Precision@3: how many of our top 3 appear in the ground-truth top 3?
  - MRR (Mean Reciprocal Rank): how high up our ranking is the ground-truth #1?
  - Sentiment agreement: how often our bucketed sentiment matches the
    synthetic label's intended bucket (sanity check on the classifier mapping).

Run with: python -m app.eval  (from backend/ directory)
"""

import csv
import sys
import time
from pathlib import Path

import mlflow

sys.path.insert(0, str(Path(__file__).parent.parent))
from app.recommender import recommend  # noqa: E402

EVAL_SET_PATH = Path(__file__).parent.parent / "data" / "eval_set.csv"


def load_eval_set() -> list[dict]:
    if not EVAL_SET_PATH.exists():
        raise FileNotFoundError(
            f"{EVAL_SET_PATH} not found. Run "
            "`python data/generate_eval_set.py` first."
        )
    with open(EVAL_SET_PATH) as f:
        return list(csv.DictReader(f))


def precision_at_k(predicted: list[str], ground_truth_top: list[str], k: int) -> float:
    pred_k = set(predicted[:k])
    gt_k = set(ground_truth_top[:k])
    if not gt_k:
        return 0.0
    return len(pred_k & gt_k) / len(gt_k)


def reciprocal_rank(predicted: list[str], gt_top1: str) -> float:
    if gt_top1 in predicted:
        return 1.0 / (predicted.index(gt_top1) + 1)
    return 0.0


def run_eval():
    rows = load_eval_set()
    p1_scores, p3_scores, mrr_scores = [], [], []
    sentiment_agree = 0
    n_severe_negative = 0

    start = time.time()

    for row in rows:
        age = int(row["age"])
        month = int(row["month"])
        text = row["text"]
        gt_ranking = [row["gt_rank_1"], row["gt_rank_2"], row["gt_rank_3"]]

        result = recommend(age=age, text=text, month=month)
        predicted = [t["id"] for t in result.ranked]

        p1_scores.append(precision_at_k(predicted, gt_ranking, 1))
        p3_scores.append(precision_at_k(predicted, gt_ranking, 3))
        mrr_scores.append(reciprocal_rank(predicted, gt_ranking[0]))

        # Loose sentiment sanity check: does our model's negative/positive
        # polarity direction agree with the synthetic label's polarity?
        true_is_negative = "Negative" in row["true_sentiment"]
        pred_is_negative = "Negative" in result.sentiment
        if true_is_negative == pred_is_negative:
            sentiment_agree += 1
        if true_is_negative and "Severe" in row["true_sentiment"]:
            n_severe_negative += 1

    elapsed = time.time() - start
    n = len(rows)

    metrics = {
        "precision_at_1": sum(p1_scores) / n,
        "precision_at_3": sum(p3_scores) / n,
        "mrr": sum(mrr_scores) / n,
        "sentiment_polarity_agreement": sentiment_agree / n,
        "avg_inference_time_sec": elapsed / n,
        "n_eval_rows": n,
    }

    tracking_dir = Path(__file__).parent.parent
    mlflow.set_tracking_uri(f"sqlite:///{tracking_dir}/mlflow.db")
    mlflow.set_experiment("calmconnect-recommender")
    with mlflow.start_run(run_name="distilbert-sentiment-rule-based-ranker-v1"):
        mlflow.log_param("sentiment_model", "distilbert-base-uncased-finetuned-sst-2-english")
        mlflow.log_param("ranker_type", "rule-based-transparent-scoring")
        mlflow.log_param("au_seasonal_signal", True)
        mlflow.log_param("n_eval_rows", n)
        for k, v in metrics.items():
            if k != "n_eval_rows":
                mlflow.log_metric(k, v)

    print("Offline eval results:")
    for k, v in metrics.items():
        print(f"  {k}: {v:.4f}" if isinstance(v, float) else f"  {k}: {v}")

    return metrics


if __name__ == "__main__":
    run_eval()
